// Calculate dynamic Hotspot Priority Index (HPI) based on multi-criteria weighting
export function calculateHpiScore(hotspot, weights = { depth: 0.35, traffic: 0.25, population: 0.20, drainage: 0.20 }) {
  const normDepth = Math.min(100, (hotspot.predictedDepth / 60) * 100);
  const normTraffic = hotspot.severity === 'CRITICAL' ? 95 : hotspot.severity === 'HIGH RISK' ? 75 : 50;
  const normPop = Math.min(100, (hotspot.populationAtRisk / 100000) * 100);
  const normDrain = Math.min(100, (hotspot.drainCapacityLoad / 180) * 100);

  const score = (
    normDepth * weights.depth +
    normTraffic * weights.traffic +
    normPop * weights.population +
    normDrain * weights.drainage
  );

  return Math.round(score * 10) / 10;
}

